        public int GetSKU_ID(string p_SKU_Code)
        {
            int sku_Id = 0;
            IDbConnection mConnection = null;
            try
            {
                mConnection = ProviderFactory.GetConnection(Configuration.ConnectionString, EnumProviders.SQLClient);
                mConnection.Open();
                uspSelectSkusByCode mSKU = new uspSelectSkusByCode();
                mSKU.Connection = mConnection;

                mSKU.SKU_Code = p_SKU_Code;

                DataTable dt = mSKU.ExecuteTable();
                if (dt.Rows.Count > 0)
                    sku_Id = int.Parse(dt.Rows[0]["SKU_ID"].ToString());
                return sku_Id;

            }
            catch (Exception exp)
            {
                ExceptionPublisher.PublishException(exp);
                return 0;
            }
            finally
            {
                if (mConnection != null && mConnection.State == ConnectionState.Open)
                {
                    mConnection.Close();
                }
            }

        }


